CHAR_ADVANCE = 6
LINE_HEIGHT = 9


def draw_char(
    fb,
    ch: str,
    x: int,
    y: int,
    color: int = 1,
    bold: bool = False,
    italic: bool = False,
    underline: bool = False,
    scale_y: int = 1,
) -> int:
    """Renders a single character with optional bold, italic, underline, and vertical scale."""
    cols = _GLYPHS_5X7.get(ch)
    if cols is None:
        cols = _GLYPHS_5X7.get("?", (0x00, 0x00, 0x00, 0x00, 0x00))

    for cx in range(5):
        col_bits = cols[cx]
        if col_bits == 0:
            continue
        for ry in range(7):
            if col_bits & (1 << ry):
                shear = 1 if (italic and ry < 3) else 0
                px = x + cx + shear
                for sy in range(scale_y):
                    py = y + ry * scale_y + sy
                    fb.pixel(px, py, color)
                    if bold:
                        fb.pixel(px + 1, py, color)

    adv = CHAR_ADVANCE + (1 if bold else 0)
    if underline:
        uy = y + 7 * scale_y
        fb.hline(x, uy, adv, color)
    return adv


def draw_text(
    fb,
    text: str,
    x: int,
    y: int,
    color: int = 1,
    bold: bool = False,
    italic: bool = False,
    underline: bool = False,
    scale_y: int = 1,
    max_width: int = None,
) -> int:
    """Draws a string and returns the final x coordinate."""
    curr_x = x
    limit_x = (x + max_width) if max_width is not None else fb.width
    for ch in text:
        adv = CHAR_ADVANCE + (1 if bold else 0)
        if curr_x + adv > limit_x:
            break
        draw_char(fb, ch, curr_x, y, color=color, bold=bold, italic=italic, underline=underline, scale_y=scale_y)
        curr_x += adv
    return curr_x


def measure_spans_px(spans: list, force_bold: bool = False) -> int:
    total = 0
    for s in spans:
        is_b = s.bold or force_bold
        adv = CHAR_ADVANCE + (1 if is_b else 0)
        total += len(s.text) * adv
    return total


def draw_bitmap_1bit(fb, bitmap: bytes, width: int, height: int, x: int, y: int, color: int = 1) -> None:
    """Blits a packed 1-bit MSB-first bitmap onto the FrameBuffer."""
    row_bytes = (width + 7) // 8
    for ry in range(height):
        for rx in range(width):
            byte_idx = ry * row_bytes + (rx >> 3)
            if byte_idx < len(bitmap) and (bitmap[byte_idx] & (0x80 >> (rx & 7))):
                fb.pixel(x + rx, y + ry, color)
